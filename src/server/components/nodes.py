# ---------------------------------------------------------------------------
# SEARCH NODE
# ---------------------------------------------------------------------------
def search_node(state: State) -> dict:
    """
    Asks the Search Agent (LLM) to decide on a good search query and request
    the web_search tool. We then actually RUN that tool ourselves and store
    the real list of URLs in state - binding a tool only makes the LLM ask
    to use it, it does not run it for you.
    """
    topic = state["topic"]

    user_prompt = f"Find recent, reliable and appropriate website URLs about the topic: {topic}"

    ai_message = search_llm_with_tools.invoke(
        [
            SystemMessage(content=SEARCH_SYSTEM_PROMPT),
            HumanMessage(content=user_prompt),
        ]
    )

    urls: list[str] = []

    for call in ai_message.tool_calls or []:
        if call["name"] == "web_search":
            result = web_search.invoke(call["args"])
            urls.extend(result)

    # remove duplicates while keeping the original order
    urls = list(dict.fromkeys(urls))

    return {"urls": urls}


# ---------------------------------------------------------------------------
# SCRAPING NODES
# ---------------------------------------------------------------------------
def route_scraping(state: State) -> list:
    """Creates one parallel branch per URL, each branch gets its own {"url": ...} state."""
    return [Send("single_scraper", {"url": url}) for url in state["urls"]]


def single_scraper(state: dict) -> dict:
    """
    Runs inside one Send() branch, so state only has the single key "url"
    (NOT the full graph State, and NOT "urls").
    """
    url = state["url"]

    user_prompt = f"Scrape the URL: {url}"

    ai_message = scraper_llm_with_tools.invoke(
        [
            SystemMessage(content=SCRAPER_SYSTEM_PROMPT),
            HumanMessage(content=user_prompt),
        ]
    )

    scraped_text = ""
    for call in ai_message.tool_calls or []:
        if call["name"] == "scrape_url":
            scraped_text = scrape_url.invoke(call["args"])

    if not scraped_text:
        scraped_text = f"No content could be scraped from {url}"

    return {"scraped_content": [scraped_text]}


# ---------------------------------------------------------------------------
# WRITER NODE
# ---------------------------------------------------------------------------
def writer_node(state: State) -> dict:
    """
    Writer node.

    Case 1:
        Called after ToolNode. Continues the existing conversation so the
        model can read the tool output and produce the final draft.

    Case 2:
        Called after START or after critic rejection. Creates a new prompt.
    """

    messages = state.get("messages", [])

    # -------------------------------------------------------
    # CASE 1: Returning from ToolNode
    # -------------------------------------------------------
    if messages and isinstance(messages[-1], ToolMessage):
        response = writer_llm_with_tools.invoke(
            [
                SystemMessage(content=WRITER_SYSTEM_PROMPT),
                *messages,
            ]
        )

        return {"messages": [response]}

    # -------------------------------------------------------
    # CASE 2: Starting a fresh draft / rewrite
    # -------------------------------------------------------
    attempt = state.get("attempt", 0) + 1

    topic = state["topic"]
    feedback = state.get("feedback", "")

    if attempt == 1:
        user_prompt = f"""
Write a detailed report about:

Topic:
{topic}

If current statistics, trends, or news are needed,
use the web search tool before writing.
"""
    else:
        user_prompt = f"""
Your previous report was rejected.

Topic:
{topic}

Reviewer Feedback:
{feedback}

Rewrite the report.

Fix every issue mentioned.

If current information is needed,
use the web search tool.
"""

    response = writer_llm_with_tools.invoke(
        [
            SystemMessage(content=WRITER_SYSTEM_PROMPT),
            *messages,
            HumanMessage(content=user_prompt),
        ]
    )

    return {
        "messages": [
            HumanMessage(content=user_prompt),
            response,
        ],
        "attempt": attempt,
    }


# ---------------------------------------------------------------------------
# EXTRACT DRAFT NODE
# ---------------------------------------------------------------------------
def extract_draft_node(state: State):
    draft = ""
    for msg in reversed(state["messages"]):
        if isinstance(msg, AIMessage):
            if isinstance(msg.content, str) and msg.content.strip():
                draft = msg.content.strip()
                break

    print("\nGenerated Draft:\n")
    print(draft)

    return {"report": draft}


# ---------------------------------------------------------------------------
# CRITIC NODE
# ---------------------------------------------------------------------------
def critic_node(state: State) -> dict:
    draft = state["report"]

    prompt = f"Review this report draft:\n{draft}\n\nGive your review or feedback."

    response = critic_llm.invoke([("system", CRITIC_SYSTEM_PROMPT), ("human", prompt)])

    review = response.content.strip()

    # The prompt forces the model to start with a "Status: APPROVED/REJECTED"
    # line, so we look at that specific line rather than scanning the whole
    # text (scanning the whole text is unreliable - the word "APPROVED" or
    # "REJECTED" can show up again later inside the Issues/Recommendations).
    status_line = review.splitlines()[0].upper() if review else ""
    is_approved = "APPROVED" in status_line and "REJECTED" not in status_line

    feedback = review  # Issues + Recommendations are useful context for a rewrite, so we keep it all

    verdict = "APPROVED" if is_approved else "REJECTED"
    print(f"[Verdict: {verdict}]")
    print(f"[Feedback]:\n{feedback}")

    return {"feedback": feedback, "is_approved": is_approved}


# ---------------------------------------------------------------------------
# ROUTERS
# ---------------------------------------------------------------------------
def should_use_tool(state: State):
    last_message = state["messages"][-1]

    if isinstance(last_message, AIMessage) and last_message.tool_calls:
        return "tools"
    return "extract_draft"


def should_stop_looping(state: State):
    if state["is_approved"]:
        print("Report has been approved\n")
        return END
    if state["attempt"] >= 3:
        print("Reached max attempts")
        return END
    return "writer"