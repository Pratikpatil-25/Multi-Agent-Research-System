scraper_llm_with_tools = llm.bind_tools([scrape_url])
writer_llm_with_tools = llm.bind_tools([web_search])
critic_llm = llm

# Single tool node, shared by whichever part of the graph needs it
# (used by the Writer <-> Tool loop below)
tool_node = ToolNode(tools)


